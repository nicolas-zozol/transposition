/* Les noms d'icône du prototype, en tirets, vers lucide-react. Les quatre icônes que le prototype trace à la main sont
   des Lucide : renvoi = CornerDownRight, branche = GitBranch, socle = Layers, carte = Workflow. */
const ICONES: Record<string, LucideIcon> = {
  'arrow-right': ArrowRight,
  ban: Ban,
  check: Check,
  'chevron-down': ChevronDown,
  'chevron-left': ChevronLeft,
  'chevron-right': ChevronRight,
  'chevron-up': ChevronUp,
  'chevrons-left': ChevronsLeft,
  'chevrons-right': ChevronsRight,
  'chevrons-up-down': ChevronsUpDown,
  'circle-alert': CircleAlert,
  'circle-check': CircleCheck,
  'circle-help': CircleHelp,
  clock: Clock,
  copy: Copy,
  download: Download,
  'file-text': FileText,
  info: Info,
  link: Link,
  'list-checks': ListChecks,
  'message-circle': MessageCircle,
  minus: Minus,
  moon: Moon,
  network: Network,
  plus: Plus,
  search: Search,
  settings: Settings,
  sun: Sun,
  'triangle-alert': TriangleAlert,
  upload: Upload,
  user: User,
  x: X,
  renvoi: CornerDownRight,
  branche: GitBranch,
  socle: Layers,
  carte: Workflow,
}

export function Icone({ nom, taille = 16, className }: { nom: string | null | undefined; taille?: number; className?: string }) {
  const C = nom ? ICONES[nom] : undefined
  if (!C) return null
  return <C aria-hidden="true" width={taille} height={taille} strokeWidth={2} className={className} style={{ width: taille, height: taille, flex: 'none' }} />
}
